-- SIS baseline schema (PostgreSQL only).
-- Sources: yoklama V1-V2 (attendance, exams) and question-pool V1-V4 (pool, agent), re-based on person/course/enrollment.

-- ---------------------------------------------------------------- core
create table person (
    id            bigint generated by default as identity primary key,
    full_name     varchar(200) not null,
    student_no    varchar(32)  unique,
    email         varchar(254) unique,          -- always stored lower-case
    username      varchar(64)  unique,          -- optional password login (staff)
    password_hash varchar(100),
    nickname      varchar(64)  not null unique, -- what other students see
    system_admin  boolean      not null default false,
    active        boolean      not null default true,
    deleted_at    timestamptz,
    created_at    timestamptz  not null default now(),
    last_login_at timestamptz
);

create table course (
    id                    bigint generated by default as identity primary key,
    code                  varchar(32)  not null,
    name                  varchar(200) not null,
    term                  varchar(16)  not null,              -- e.g. 2026-FALL
    language              varchar(8)   not null default 'tr',
    attendance_enabled    boolean      not null default true,
    pool_enabled          boolean      not null default false,
    questions_per_chapter integer      not null default 2,
    ask_ai_per_day        integer      not null default 10,
    ai_context            text         not null default '',   -- course description given to the AI
    archived_at           timestamptz,
    created_at            timestamptz  not null default now(),
    constraint uq_course_code_term unique (code, term)
);

create table enrollment (
    id         bigint generated by default as identity primary key,
    course_id  bigint      not null references course(id) on delete cascade,
    person_id  bigint      not null references person(id),
    role       varchar(16) not null check (role in ('OWNER', 'INSTRUCTOR', 'ASSISTANT', 'STUDENT')),
    deleted_at timestamptz,                                   -- soft removal from the course
    created_at timestamptz not null default now(),
    constraint uq_enrollment unique (course_id, person_id)
);
create index ix_enrollment_person on enrollment(person_id);

create table chapter (
    id        bigint generated by default as identity primary key,
    course_id bigint  not null references course(id) on delete cascade,
    number    integer not null,
    title     text    not null,
    doc_en    text    not null default '',
    doc_tr    text    not null default '',
    open      boolean not null default true,
    constraint uq_chapter unique (course_id, number)
);

create table login_token (
    token_hash text primary key,
    person_id  bigint      not null references person(id) on delete cascade,
    created_at timestamptz not null default now(),
    expires_at timestamptz not null,
    used_at    timestamptz
);

create table user_session (
    token_hash text primary key,
    person_id  bigint      not null references person(id) on delete cascade,
    created_at timestamptz not null default now(),
    expires_at timestamptz not null
);
create index ix_user_session_person on user_session(person_id);

-- ---------------------------------------------------------------- attendance
create table classroom (
    id             bigint generated by default as identity primary key,
    owner_id       bigint        not null references person(id),
    name           varchar(120)  not null,
    latitude       double precision,
    longitude      double precision,
    radius_m       integer,
    ble_beacon_id  varchar(16),
    ble_key_hex    varchar(64),
    created_at     timestamptz   not null
);

create table class_session (
    id                            bigint generated by default as identity primary key,
    course_id                     bigint       not null references course(id),
    classroom_id                  bigint       references classroom(id),
    title                         varchar(200) not null,
    code                          varchar(6)   not null,
    status                        varchar(16)  not null,
    duration_minutes              integer      not null,
    refresh_ms                    integer      not null,
    required_scans                integer      not null,
    max_span_slots                integer      not null,
    max_token_age_ms              integer      not null,
    latency_margin_ms             integer      not null,
    default_latency_threshold_ms  integer      not null,
    screen_area_ratio_threshold   double precision not null,
    geo_mode                      varchar(16)  not null,
    ble_mode                      varchar(16)  not null,
    frame_capture                 boolean      not null,
    epoch_start_ms                bigint,
    opened_at                     timestamptz,
    closes_at                     timestamptz,
    closed_at                     timestamptz,
    baseline_latency_ms           integer,
    baseline_area_ratio_max       double precision,
    created_at                    timestamptz  not null
);
create index ix_session_code_status on class_session(code, status);

create table calibration_run (
    id               bigint generated by default as identity primary key,
    session_id       bigint       not null references class_session(id) on delete cascade,
    label            varchar(32)  not null,
    min_latency_ms   integer      not null,
    max_area_ratio   double precision not null,
    valid_scan_count integer      not null,
    clock_rtt_ms     integer      not null,
    created_at       timestamptz  not null
);

create table checkin_attempt (
    id                    uuid primary key,
    session_id            bigint       not null references class_session(id) on delete cascade,
    student_no            varchar(32)  not null,
    device_id             varchar(32)  not null,
    ip                    varchar(64),
    user_agent            varchar(512),
    state                 varchar(16)  not null,
    result_code           varchar(32),
    frame_path            varchar(255),
    frame_seq             integer,
    ble_nonce             varchar(16),
    ble_nonce_expires_ms  bigint,
    ble_verified          boolean      not null default false,
    sync1_offset_ms       integer,
    sync1_rtt_ms          integer,
    created_at            timestamptz  not null,
    expires_at            timestamptz  not null
);
create index ix_attempt_session on checkin_attempt(session_id);

create table scan_record (
    id                   bigint generated by default as identity primary key,
    attempt_id           uuid         not null references checkin_attempt(id) on delete cascade,
    raw_token            varchar(64)  not null,
    seq                  integer,
    ts_ms                bigint,
    first_seen_server_ms bigint       not null,
    arrival_ms           bigint       not null,
    frame_time_source    varchar(16)  not null,
    frame_w              integer      not null,
    frame_h              integer      not null,
    corners              varchar(400),
    area_ratio           double precision,
    valid                boolean      not null,
    reason               varchar(32),
    clock_suspect        boolean      not null default false,
    duplicate            boolean      not null default false
);
create index ix_scan_attempt on scan_record(attempt_id);

-- Attendance is only for enrolled students: person_id is mandatory.
-- student_no / full_name are a snapshot taken when the row is written (CSV export, history).
create table attendance (
    id                    bigint generated by default as identity primary key,
    session_id            bigint       not null references class_session(id) on delete cascade,
    person_id             bigint       not null references person(id),
    student_no            varchar(32)  not null,
    full_name             varchar(200),
    source                varchar(16)  not null,
    attempt_id            uuid,
    device_id             varchar(32),
    status                varchar(16)  not null,
    flags                 varchar(500) not null default '',
    min_latency_ms        integer,
    latency_threshold_ms  integer,
    threshold_source      varchar(16),
    area_ratio_max        double precision,
    area_threshold        double precision,
    geo_state             varchar(16)  not null default 'OFF',
    geo_lat               double precision,
    geo_lng               double precision,
    geo_accuracy_m        double precision,
    geo_distance_m        double precision,
    clock_offset_ms       integer,
    clock_rtt_ms          integer,
    camera_id_hash        varchar(64),
    camera_label          varchar(200),
    user_agent            varchar(512),
    ble_verified          boolean      not null default false,
    frame_path            varchar(255),
    teacher_decision      varchar(16)  not null default 'NONE',
    teacher_note          varchar(500),
    decided_at            timestamptz,
    created_at            timestamptz  not null,
    constraint uq_att_student unique (session_id, student_no),
    constraint uq_att_person  unique (session_id, person_id),
    constraint uq_att_device  unique (session_id, device_id)
);
create index ix_att_session on attendance(session_id);
create index ix_att_person on attendance(person_id);

-- ---------------------------------------------------------------- question pool
create table question (
    id              bigint generated by default as identity primary key,
    chapter_id      bigint not null references chapter(id),
    author_id       bigint not null references person(id),
    stem            text   not null,
    option_a        text   not null,
    option_b        text   not null,
    option_c        text   not null,
    option_d        text   not null,
    correct         char(1) not null check (correct in ('A', 'B', 'C', 'D')),
    rationale_a     text   not null,
    rationale_b     text   not null,
    rationale_c     text   not null,
    rationale_d     text   not null,
    reference       text   not null,
    status          text   not null default 'PENDING'
        check (status in ('PENDING', 'NEEDS_REVISION', 'APPROVED', 'REJECTED')),
    ai_status       text   not null default 'NONE'
        check (ai_status in ('NONE', 'RUNNING', 'DONE', 'FAILED', 'SKIPPED')),
    ai_review       jsonb,
    instructor_note text,
    explanation     text,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),
    approved_at     timestamptz
);
create index ix_question_chapter on question(chapter_id, status);
create index ix_question_author on question(author_id);

-- First answer of a student to a question (the only one that counts). Was "attempt" in question-pool.
create table question_attempt (
    id          bigint generated by default as identity primary key,
    question_id bigint  not null references question(id) on delete cascade,
    person_id   bigint  not null references person(id) on delete cascade,
    selected    char(1) not null check (selected in ('A', 'B', 'C', 'D')),
    correct     boolean not null,
    created_at  timestamptz not null default now(),
    constraint uq_question_attempt unique (question_id, person_id)
);
create index ix_question_attempt_person on question_attempt(person_id);

create table question_comment (
    id          bigint generated by default as identity primary key,
    question_id bigint not null references question(id) on delete cascade,
    author_id   bigint references person(id) on delete cascade,
    is_ai       boolean not null default false,
    parent_id   bigint references question_comment(id) on delete cascade,
    body        text   not null,
    deleted     boolean not null default false,
    created_at  timestamptz not null default now()
);
create index ix_question_comment_question on question_comment(question_id);

create table question_flag (
    id          bigint generated by default as identity primary key,
    question_id bigint not null references question(id) on delete cascade,
    person_id   bigint not null references person(id) on delete cascade,
    reason      text   not null,
    resolved    boolean not null default false,
    created_at  timestamptz not null default now()
);

-- ---------------------------------------------------------------- exams (unified)
-- yoklama's exam (questions + per-student results) plus question-pool's paper builder (forms, seed, pool link).
create table exam (
    id          bigint generated by default as identity primary key,
    course_id   bigint       not null references course(id),
    title       varchar(200) not null,
    exam_date   date,
    forms       integer      not null default 1 check (forms between 1 and 4),
    seed        bigint,                                  -- shuffle seed when the paper was drawn from the pool
    created_at  timestamptz  not null
);
create index ix_exam_course on exam(course_id);

create table exam_question (
    id               bigint generated by default as identity primary key,
    exam_id          bigint        not null references exam(id) on delete cascade,
    position         integer       not null,
    type             varchar(16)   not null,
    text             varchar(2000),
    topic            varchar(120),
    max_points       numeric(7,2)  not null,
    choice_count     integer,
    correct_choice   varchar(1),
    pool_question_id bigint        references question(id) on delete set null
);
create index ix_exam_question_exam on exam_question(exam_id);

create table exam_result (
    id          bigint generated by default as identity primary key,
    exam_id     bigint       not null references exam(id) on delete cascade,
    person_id   bigint       not null references person(id),
    student_no  varchar(32)  not null,
    full_name   varchar(200) not null default '',
    form        varchar(1),
    note        varchar(500),
    created_at  timestamptz  not null,
    updated_at  timestamptz  not null,
    constraint uq_exam_result unique (exam_id, student_no),
    constraint uq_exam_result_person unique (exam_id, person_id)
);

create table exam_answer (
    id           bigint generated by default as identity primary key,
    result_id    bigint       not null references exam_result(id) on delete cascade,
    question_id  bigint       not null references exam_question(id) on delete cascade,
    answer_text  varchar(2000),
    points       numeric(7,2),
    constraint uq_exam_answer unique (result_id, question_id)
);
create index ix_exam_answer_question on exam_answer(question_id);

-- ---------------------------------------------------------------- AI agents (MCP)
create table mcp_token (
    token_hash   text primary key,
    person_id    bigint not null unique references person(id) on delete cascade,
    hint         text   not null,
    created_at   timestamptz not null default now(),
    last_used_at timestamptz
);

create table study_state (
    person_id  bigint not null references person(id) on delete cascade,
    chapter_id bigint not null references chapter(id) on delete cascade,
    status     text   not null default 'NOT_STARTED'
        check (status in ('NOT_STARTED', 'STUDYING', 'REVIEWING', 'DONE')),
    confidence integer check (confidence between 1 and 5),
    notes      text   not null default '',
    updated_at timestamptz not null default now(),
    primary key (person_id, chapter_id)
);

create table practice_answer (
    id          bigint generated by default as identity primary key,
    person_id   bigint  not null references person(id) on delete cascade,
    question_id bigint  not null references question(id) on delete cascade,
    selected    char(1) not null check (selected in ('A', 'B', 'C', 'D')),
    correct     boolean not null,
    created_at  timestamptz not null default now()
);
create index ix_practice_answer_person on practice_answer(person_id, question_id, id);

create table study_log (
    id         bigint generated by default as identity primary key,
    person_id  bigint not null references person(id) on delete cascade,
    chapter_id bigint references chapter(id) on delete cascade,
    summary    text   not null,
    created_at timestamptz not null default now()
);
create index ix_study_log_person on study_log(person_id, id);

-- Question groups (a shared stem with sub-questions 5a, 5b, …), per-question choice labels (A-D, D/Y, T/F, 1/0, …)
-- and rich (HTML) content for questions and groups. Scoring stays per exam_question; a group is only presentation.
create table exam_question_group (
    id       bigint  generated by default as identity primary key,
    exam_id  bigint  not null references exam(id) on delete cascade,
    position integer not null,          -- number printed on the paper; shares the numbering with ungrouped questions
    text     text,                      -- common stem (plain text, code fences as in question text)
    html     text                       -- rich content; sanitized on display (DOMPurify)
);
create index ix_exam_question_group_exam on exam_question_group(exam_id);

alter table exam_question add column group_id      bigint references exam_question_group(id) on delete set null;
alter table exam_question add column sub_label     varchar(8);     -- 'a', 'b', … inside a group
alter table exam_question add column html          text;           -- rich content of the question
alter table exam_question add column choice_labels varchar(16);    -- one character per option, e.g. 'ABCD', 'DY', '10'
create index ix_exam_question_group on exam_question(group_id);

update exam_question set choice_labels = left('ABCDEFGHIJ', choice_count)
 where type = 'CHOICE' and choice_count is not null and choice_count between 1 and 10;

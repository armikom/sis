create table topic (
    id         bigint generated by default as identity primary key,
    chapter_id bigint  not null references chapter(id) on delete cascade,
    number     integer not null,               -- the N of the "## N. Title" heading in the chapter text
    title_en   text    not null default '',
    title_tr   text    not null default '',
    constraint uq_topic unique (chapter_id, number)
);
create table question_topic (
    question_id bigint not null references question(id) on delete cascade,
    topic_id    bigint not null references topic(id) on delete cascade,
    primary key (question_id, topic_id)
);
create index ix_question_topic_topic on question_topic(topic_id);
create table exam_question_topic (
    exam_question_id bigint not null references exam_question(id) on delete cascade,
    topic_id         bigint not null references topic(id) on delete cascade,
    primary key (exam_question_id, topic_id)
);
alter table exam add column published boolean not null default false;  -- students see results only when true
alter table exam_question alter column text type text;          -- was varchar(2000)
alter table exam_question add column explanation text;          -- overall explanation of the answer
create table exam_question_option (
    exam_question_id bigint     not null references exam_question(id) on delete cascade,
    letter           varchar(1) not null,                       -- 'A'..'F', as printed on the exam
    text             text       not null default '',
    rationale        text,                                      -- why this option is right / wrong
    primary key (exam_question_id, letter)
);
